
	include "demosystem/linker_common.asm" ; TODO include it inside basm as it is so useful

	org 0x100
	
	
	run $
	di
		ld hl, 0xc9fb
		ld (0x38), hl
		ld sp, $
	ei


	SELECTED_CRUNCHER = CRUNCHER_ZX0 : MOVE_CRUNCHED_DATA(C4_4000, 0x8000)
	ld bc, 0x7fc4 : out (c), c
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : INDIRECT_UNCRUNCH(0x8000, C4_4000, 0x4000)

	ld bc, 0x7fc0 : out (c), c
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : MOVE_CRUNCHED_DATA(C6_4000, 0x8000)
	ld bc, 0x7fc6 : out (c), c
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : INDIRECT_UNCRUNCH(0x8000, C6_4000, 0x4000)

	ld bc, 0x7fc5 : out (c), c
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : UNCRUNCH(C5_4000, 0x4000)


	ld bc, 0x7fc0 : out (c), c
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : UNCRUNCH(C0_8000, 0x8000)
	SELECTED_CRUNCHER = CRUNCHER_ZX0_BACKWARD : UNCRUNCH(C0_300, 0x0300) ; backward

	jp 0x300

	SELECTED_CRUNCHER = CRUNCHER_ZX0 : INSTALL_UNCRUNCHER()
	SELECTED_CRUNCHER = CRUNCHER_ZX0_BACKWARD : INSTALL_UNCRUNCHER()
	
	SELECTED_CRUNCHER = CRUNCHER_ZX0_BACKWARD : LOAD_N_CRUNCH(C0_300, "C0.300")
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : LOAD_N_CRUNCH(C5_4000, "C5.4000")
	assert $<0x4000, "we will have bank issues there"
	assert $<0x8000
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : LOAD_N_CRUNCH(C6_4000, "C6.4000")
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : LOAD_N_CRUNCH(C0_8000, "C0.8000")
	SELECTED_CRUNCHER = CRUNCHER_ZX0 : LOAD_N_CRUNCH(C4_4000, "C4.4000")
	assert $>0x4000, "if not there is no need any more to move the data"
	assert $<0x8000





	SAVE 'BIRTHTRO', , , DSK, 'BIRTHTRO.DSK'